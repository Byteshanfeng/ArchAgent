#!/usr/bin/env python3
import sys
import os
import hashlib
from PIL import Image, ImageDraw
sys.path.insert(0, os.path.dirname(__file__))
from cad_io import load_cad_document

def get_cache_key(filepath):
    st = os.stat(filepath)
    raw = f"cad-entities-v3:{filepath}:{st.st_size}:{int(st.st_mtime)}"
    return hashlib.md5(raw.encode('utf-8')).hexdigest()[:12]

def process_skp(filepath, out_png):
    with open(filepath, 'rb') as f:
        data = f.read()
    png_start = data.find(b'\x89PNG\r\n\x1a\n')
    if png_start == -1:
        raise RuntimeError("未在 SKP 文件中找到内置预览图像")
    iend = data.find(b'IEND', png_start)
    if iend == -1:
        raise RuntimeError("SKP 内置 PNG 数据不完整")
    png_bytes = data[png_start:iend+8]
    tmp_thumb = out_png + ".raw.png"
    with open(tmp_thumb, 'wb') as out:
        out.write(png_bytes)

    im = Image.open(tmp_thumb).convert("RGB")
    bg = Image.new("RGB", (1024, 1024), (255, 255, 255))
    # Maintain aspect ratio inside 820x820
    im.thumbnail((820, 820), Image.Resampling.LANCZOS)
    ox = (1024 - im.width) // 2
    oy = (1024 - im.height) // 2
    bg.paste(im, (ox, oy))
    bg.save(out_png)
    try:
        os.remove(tmp_thumb)
    except OSError:
        pass

COLOR_MAP = {
    'black': (225, 232, 240),
    'white': (240, 245, 250),
    'red': (248, 113, 113),
    'yellow': (250, 204, 21),
    'green': (74, 222, 128),
    'cyan': (56, 189, 248),
    'blue': (96, 165, 250),
    'magenta': (232, 121, 249),
}

def parse_color(c):
    c = c.lower()
    if c in COLOR_MAP:
        return COLOR_MAP[c]
    if c.startswith('#') and len(c) == 7:
        try:
            r, g, b = int(c[1:3], 16), int(c[3:5], 16), int(c[5:7], 16)
            if r < 45 and g < 45 and b < 45:
                return (215, 225, 235)
            return (r, g, b)
        except Exception:
            pass
    return (210, 220, 235)

def process_dwg(filepath, out_png):
    # Reuse the CAD entity renderer so the model sees the same lines that are measured.
    from cad_dwg_generator import render_dxf_preview
    doc = load_cad_document(filepath)
    render_dxf_preview(doc, out_png, title_text=os.path.basename(filepath))
    if not os.path.isfile(out_png):
        raise RuntimeError("CAD 图纸没有可预览的图元")


def process_obj(filepath, out_png):
    vertices = []
    edges = set()
    with open(filepath, 'r', encoding='utf-8', errors='replace') as f:
        for line in f:
            if line.startswith('v '):
                parts = line.split()
                if len(parts) >= 4:
                    vertices.append(tuple(float(v) for v in parts[1:4]))
            elif line.startswith('f '):
                ids = []
                for part in line.split()[1:]:
                    index = int(part.split('/')[0])
                    ids.append(index - 1 if index > 0 else len(vertices) + index)
                for a, b in zip(ids, ids[1:] + ids[:1]):
                    if 0 <= a < len(vertices) and 0 <= b < len(vertices):
                        edges.add(tuple(sorted((a, b))))
    if not vertices or not edges:
        raise RuntimeError("OBJ 文件没有可预览的面或线")

    # OBJ generated by this app uses Y as the vertical axis.
    projected = [(x - z * 0.65, -y + (x + z) * 0.28) for x, y, z in vertices]
    xs, ys = [p[0] for p in projected], [p[1] for p in projected]
    min_x, min_y = min(xs), min(ys)
    span_x, span_y = max(xs) - min_x, max(ys) - min_y
    scale = min(900 / max(span_x, 1), 900 / max(span_y, 1))
    image = Image.new('RGB', (1024, 1024), (15, 18, 24))
    draw = ImageDraw.Draw(image)
    for a, b in list(edges)[:80000]:
        pa, pb = projected[a], projected[b]
        draw.line([(62 + (pa[0] - min_x) * scale, 962 - (pa[1] - min_y) * scale),
                   (62 + (pb[0] - min_x) * scale, 962 - (pb[1] - min_y) * scale)],
                  fill=(210, 228, 240), width=2)
    image.save(out_png)

def main():
    filepath = sys.argv[1]
    uploads_dir = sys.argv[2]
    if not os.path.exists(filepath):
        print(f"ERROR:文件不存在: {filepath}")
        sys.exit(1)

    ext = os.path.splitext(filepath)[1].lower()
    key = get_cache_key(filepath)
    out_filename = f"parsed_{key}.png"
    out_path = os.path.join(uploads_dir, out_filename)

    if os.path.exists(out_path) and os.path.getsize(out_path) > 1000:
        print(f"OK:{out_filename}")
        sys.exit(0)

    if ext == '.skp':
        process_skp(filepath, out_path)
    elif ext in ('.dwg', '.dxf'):
        process_dwg(filepath, out_path)
    elif ext == '.obj':
        process_obj(filepath, out_path)
    elif ext in ('.png', '.jpg', '.jpeg', '.webp'):
        im = Image.open(filepath).convert('RGB')
        im.save(out_path)
    else:
        print(f"ERROR:暂不支持的文件后缀: {ext}")
        sys.exit(1)

    print(f"OK:{out_filename}")

if __name__ == '__main__':
    main()
